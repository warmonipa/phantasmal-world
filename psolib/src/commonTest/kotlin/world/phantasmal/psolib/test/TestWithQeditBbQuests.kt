/**
 * Applies [process] to all qedit Wiki BB quest fixtures shipped under
 * [QUEST_RESOURCE_PREFIX]. Mirrors [testWithTetheallaQuests] but covers a
 * different corpus (qedit.info Wiki catalog: Battle / Challenge / Ep I/II/IV).
 *
 * Source: https://qedit.info/index.php?title=Quests — every BB quest with
 * a Download link as of 2026-05-17. English variant preferred (`_e.qst`);
 * Japanese variant (`_j.qst`) used where no English translation exists.
 */
inline fun testWithQeditBbQuests(process: (path: String, filename: String) -> Unit) {
    for (file in QEDIT_BB_QUESTS) {
        val lastSlashIdx = file.lastIndexOf('/')
        process(QUEST_RESOURCE_PREFIX + file, file.drop(lastSlashIdx + 1))
    }
}

